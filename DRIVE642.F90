! REQUIRED ROUTINES - CUBGCV, SPINT1, SPFIT1, SPCOF1, SPERR1, GGRAND

! REMARKS   USES SUBROUTINE CUBGCV TO FIT A CUBIC SMOOTHING SPLINE
!           TO 50 DATA POINTS WHICH ARE GENERATED BY ADDING A RANDOM
!           VARIABLE WITH UNIFORM DENSITY IN THE INTERVAL [-0.3,0.3]
!           TO 50 POINTS SAMPLED FROM THE CURVE  Y=SIN(3*PI*X/2).
!           RANDOM DEVIATES IN THE INTERVAL [0,1] ARE GENERATED BY THE
!           DOUBLE PRECISION FUNCTION GGRAND (SIMILAR TO IMSL FUNCTION
!           GGUBFS).  THE ABSCISSAE ARE UNEQUALLY SPACED IN [0,1].

!           POINT STANDARD ERROR ESTIMATES ARE RETURNED IN SE BY
!           SETTING JOB=1.  THE ERROR VARIANCE ESTIMATE IS RETURNED
!           IN VAR.  IT COMPARES FAVOURABLY WITH THE TRUE VALUE OF 0.03.
!           SUMMARY STATISTICS FROM THE ARRAY WK ARE WRITTEN TO
!           UNIT 6.  DATA VALUES AND FITTED VALUES WITH ESTIMATED
!           STANDARD ERRORS ARE ALSO WRITTEN TO UNIT 6.

USE Cubic_Spline_GCV
IMPLICIT NONE

INTEGER, PARAMETER  :: n = 50, ic = 49

INTEGER    :: i, job, ier
REAL (dp)  :: x(n), f(n), y(n), df(n), c(ic,3), wk(7*(n+2)), var, se(n)
REAL (dp)  :: dseed, randno

!---INITIALIZE---
dseed = 1.2345D4
job = 1
var = -1.0D0

!---CALCULATE DATA POINTS---
DO  i = 1, n
  CALL ggrand(dseed, randno)
  x(i) = (i-0.5) / n + (2.0*randno - 1.0) / (3.0*n)
  CALL ggrand(dseed, randno)
  f(i) = SIN(4.71238*x(i)) + (2.0*randno - 1.0) * 0.3
  df(i) = 1.0D0
END DO

!---FIT CUBIC SPLINE---
CALL cubgcv(x, f, df, n, y, c, ic, var, job, se, wk, ier)

!---WRITE OUT RESULTS---
WRITE (6,5000)
WRITE (6,5100) ier, var, wk(3), wk(4), wk(2)
WRITE (6,5200)
DO  i = 1, n - 1
  WRITE (6,5300) i, x(i), f(i), y(i), se(i), c(i,1:3)
END DO
WRITE (6,5300) n, x(n), f(n), y(n), se(n)
STOP


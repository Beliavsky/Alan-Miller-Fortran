SUBROUTINE ggrand(dseed, fn_val)

! REAL (dp) UNIFORM RANDOM NUMBER GENERATOR

! CONSTANTS: A = 7**5
!            B = 2**31 - 1
!            C = 2**31

! REFERENCE: IMSL MANUAL, CHAPTER G - GENERATION AND TESTING OF RANDOM NUMBERS

!---SPECIFICATIONS FOR ARGUMENTS---

REAL (dp), INTENT(IN OUT)  :: dseed
REAL (dp), INTENT(OUT)     :: fn_val

!---SPECIFICATIONS FOR LOCAL VARIABLES---
REAL (dp)             :: s
REAL (dp), PARAMETER  :: a = 16807.0D0, b = 2147483647.0D0, c = 2147483648.0D0

s = dseed
s = MOD(a*s, b)
fn_val = s / c
dseed  = s
RETURN
END SUBROUTINE ggrand


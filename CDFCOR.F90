!
!  METHOD 1  THE USER SUPPLIES AN INITIAL APPROXIMATION (SEE
!            OPTION 7 ABOVE).
!
!  METHOD 2  ONE ITERATION OF LOEBS ALGORITHM IS PERFORMED, THAT
!            IS, SUBROUTINE SLNPRO IS USED TO SOLVE THE PROBLEM
!                MINIMIZE MAX(ABS(F*Q-WT*P))
!                SUBJECT TO Q >= MAX(0.00001,10000.0*B**(-T))
!                EVERYWHERE ON THE GRID, ABS(Q(J)) <= 1.0
!                FOR J=1,...,NUMQ (AND THE OTHER
!                INEQUALITY CONSTRAINTS).
!            IF WE ARE PLACING A LOWER BOUND ON THE DENOMINATOR
!            IN THE MAIN ITERATIONS, THE LOWER BOUND HERE IS
!            INCREASED (IF NECESSARY) TO MATCH THAT BOUND.
!            IF SLNPRO FAILS TO PRODUCE AN APPROXIMATION P/Q WE
!            TRY WITH BOTH LOOSENED AND TIGHTENED TOLERANCES.
!
!  METHOD 3  THE INITIAL APPROXIMATION IS TAKEN TO BE P/Q=
!            0.0/PWR(.,NUMP+1).
!

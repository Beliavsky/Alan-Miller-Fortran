! OF THREE METHODS, WITH THE USER BEING ABLE TO SELECT THE FIRST
! OR (BY DEFAULT) THE SECOND.  IF A METHOD FAILS, THE PROGRAM
! WILL TRY THE NEXT METHOD IN THE SEQUENCE.  FAILURE OF A METHOD
! MEANS EITHER NO RATIONAL APPROXIMATION P/Q COULD BE PRODUCED,
! OR ONE WAS PRODUCED WHICH VIOLATED SOME CONSTRAINT BY MORE THAN
! EPRES, OR WHICH HAD A DENOMINATOR WHICH WAS VERY SMALL IN
! ABSOLUTE VALUE OR NEGATIVE AT SOME POINT (AND THE MAIN
! ALGORITHM WAS UNABLE TO CORRECT THIS PROBLEM).
